#!/usr/bin/env python3
"""Generate overlay/src/panfrost/vulkan/00-panvk-defaults.conf from compat/game-profiles.json.

The output keeps the base project's entries (copied from the base conf, whose sha256 is pinned in
game-profiles.json) and appends one <application> per game.

Usage: tools/gen_driconf.py --base-conf work/mesa/src/panfrost/vulkan/00-panvk-defaults.conf [--check]
  --check  exit 1 if the committed overlay differs from what would be generated (used in CI).
"""
import argparse, hashlib, json, pathlib, re, sys
from xml.sax.saxutils import quoteattr

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROFILES = ROOT / "compat" / "game-profiles.json"
OUT = ROOT / "overlay" / "src" / "panfrost" / "vulkan" / "00-panvk-defaults.conf"
KNOWN_OPTIONS = {"pan_env_defaults", "heap_memory_percent", "vk_x11_override_min_image_count",
                 "vk_x11_strict_image_count", "vk_wsi_force_swapchain_to_current_extent",
                 "vk_x11_ignore_suboptimal", "pan_enable_vertex_pipeline_stores_atomics"}


def exe_regex(exe):
    """POSIX ERE (driconf uses regexec) matching the whole name, case-insensitively.

    Windows file names are case-insensitive, and DXVK passes the name as it is on disk.
    Special characters become bracket expressions ("[.]") rather than backslash escapes:
    Mesa embeds driconf into a C string on Android, where "\\." would lose its backslash."""
    out = []
    for ch in exe:
        if ch.isalpha():
            out.append(f"[{ch.upper()}{ch.lower()}]")
        elif ch in ".()+*?{}|$":
            out.append(f"[{ch}]")
        elif ch in "[]^\\\"":
            sys.exit(f"unsupported character {ch!r} in exe name {exe!r}")
        else:
            out.append(ch)
    return "^" + "".join(out) + "$"


def generate(base_conf_text, data):
    m = re.search(r"<device driver=\"panvk\">(.*)</device>", base_conf_text, re.S)
    if not m:
        sys.exit("base conf has no <device driver=\"panvk\"> section")
    base_body = m.group(1).rstrip()
    out = ['<?xml version="1.0"?>',
           "<!-- Generated by tools/gen_driconf.py from compat/game-profiles.json. Do not edit. -->",
           "<driconf>",
           '    <device driver="panvk">',
           "        <!-- Base project (panvk-kbase-android) entries -->",
           base_body.strip("\n"), ""]
    seen = set()
    for g in data["groups"]:
        for k in g["options"]:
            if k not in KNOWN_OPTIONS:
                sys.exit(f"{g['id']}: unknown driconf option {k}")
        out.append(f"        <!-- {g['id']}: {g['title']} -->")
        for app in g["apps"]:
            exe = app["exe"]
            if exe.lower() in seen:
                sys.exit(f"duplicate exe {exe}")
            seen.add(exe.lower())
            out.append(f"        <application name={quoteattr(app['name'])} "
                       f"application_name_match={quoteattr(exe_regex(exe))}>")
            for k, v in g["options"].items():
                out.append(f"            <option name={quoteattr(k)} value={quoteattr(str(v))} />")
            out.append("        </application>")
        out.append("")
    out += ["    </device>", "</driconf>", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base-conf", required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    data = json.loads(PROFILES.read_text())
    base = pathlib.Path(a.base_conf).read_bytes()
    sha = hashlib.sha256(base).hexdigest()
    if sha != data["baseConfSha256"]:
        sys.exit(f"base conf sha256 {sha} != pinned {data['baseConfSha256']}: review the base change, then update baseConfSha256")
    text = generate(base.decode(), data)
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run tools/gen_driconf.py --base-conf {a.base_conf}")
        print("OK driconf overlay up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({sum(len(g['apps']) for g in data['groups'])} apps)")


if __name__ == "__main__":
    main()
